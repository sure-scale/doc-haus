import { afterEach, describe, expect, test } from "bun:test"
import { createElement } from "react"
import { renderToStaticMarkup } from "react-dom/server"
import { VERSION_ORIGINS } from "../../../services/ingest/src/document-versions"
import { compareUrl } from "../src/api/ingest/compare"
import { fetchVersionBytes, restoreVersion, RestoreRefusedError, VersionUnavailableError, type DocumentVersion, type DocumentVersions } from "../src/api/ingest/versions"
import { choiceParams } from "../src/components/CompareDialog"
import VersionsPanel, { branchNote, previousVersion, restoreConfirmText, unavailableReason, versionActor, versionOption, versionOrigin } from "../src/components/DocumentVersions"

const originalFetch = globalThis.fetch
afterEach(() => {
  globalThis.fetch = originalFetch
})

const at = Date.UTC(2026, 9, 24, 9)
const version = (number: number, patch: Partial<DocumentVersion> = {}): DocumentVersion => ({
  id: `v-${number}`, number, sha256: String(number).repeat(64), ext: ".docx", bytes: 1000, parent: number > 1 ? `v-${number - 1}` : null,
  derived_from: null, origin: "revision", actor: "unknown", run: null, label: null, created_at: at + number * 60_000, current: false, ...patch,
})

describe("version words", () => {
  test("each writer reads in plain words, and an unknown one still reads as a save", () => {
    const words = (origin: string, parent: string | null = "v-0") => versionOrigin({ id: "v", origin: origin as DocumentVersion["origin"], parent })
    expect(["upload", "replace", "generated", "revision", "agent-edit", "redaction", "accept", "conversion", "copy", "system", "unknown"].map((origin) => words(origin))).toEqual([
      "Uploaded", "Uploaded as a new version", "Generated by doc.haus", "Saved from Word", "Edited by doc.haus", "Redacted",
      "Changes accepted", "Converted from PDF", "Copied from another document", "Updated by doc.haus", "Changed outside doc.haus",
    ])
    expect(words("from-a-newer-ingest")).toBe("Saved")
    // Every origin the ingest service writes has its own words, first version or later.
    for (const origin of VERSION_ORIGINS) for (const parent of [null, "v-0"]) expect(words(origin, parent)).not.toBe("Saved")
  })

  test("a first version doc.haus wrote was added, and a file found changed between kept versions changed outside doc.haus", () => {
    const words = (origin: DocumentVersion["origin"], parent: string | null) => versionOrigin({ id: "v", origin, parent })
    expect([words("system", null), words("system", "v-1")]).toEqual(["Added by doc.haus", "Updated by doc.haus"])
    expect([words("unknown", null), words("unknown", "v-1")]).toEqual(["Earlier file, not recorded how it was made", "Changed outside doc.haus"])
  })

  test("a picker option leaves out the year, which its title keeps", () => {
    const option = versionOption(version(3, { origin: "revision", created_at: Date.UTC(2026, 9, 24, 9) }), [])
    expect(option.text).toBe("Version 3 · Saved from Word · 24 Oct")
    expect(option.title).toStartWith("Version 3 · Saved from Word · 24 Oct 2026")
  })

  test("a restore names the version it brought back from its event", () => {
    const restored = version(5, { origin: "restore" })
    const event = { id: 1, kind: "restore" as const, version_id: "v-5", actor: "unknown", detail: { restored_from: "v-2", restored_number: 2 }, created_at: at }
    expect(versionOrigin(restored, [event])).toBe("Restored from version 2")
    expect(versionOrigin(restored, [])).toBe("Restored")
  })

  test("replies added from their changes with no decision read as replies, not as a save from Word", () => {
    expect([version(2, { label: "1 reply added" }), version(3, { label: "2 replies added" })].map((v) => versionOrigin(v))).toEqual(["Replies added", "Replies added"])
    expect([version(4), version(5, { label: "Signed copy, 2 replies added" })].map((v) => versionOrigin(v))).toEqual(["Saved from Word", "Saved from Word"])
  })

  test("an actor shows only when the writer knew a person", () => {
    expect(["unknown", "", "doc.haus", "agent:legal-review"].map(versionActor)).toEqual([undefined, undefined, undefined, undefined])
    expect(versionActor(null)).toBeUndefined()
    expect(versionActor(" Pat Reviewer ")).toBe("Pat Reviewer")
  })

  test("versions made from the same version are both marked as based on it, never merged", () => {
    const list = [version(4, { parent: "v-2" }), version(3), version(2), version(1)]
    expect(list.map((v) => branchNote(v, list))).toEqual(["Based on version 2", "Based on version 2", undefined, undefined])
  })

  test("the working file compares with the version before its current one, or that one when the file changed outside doc.haus", () => {
    const list = [version(3, { current: true }), version(2), version(1)]
    expect(previousVersion({ versions: list, working_version: "v-3" })?.id).toBe("v-2")
    expect(previousVersion({ versions: list, working_version: null })?.id).toBe("v-3")
    expect(previousVersion({ versions: [version(1, { current: true })], working_version: "v-1" })).toBeUndefined()
    expect(previousVersion({ versions: [], working_version: null })).toBeUndefined()
  })
})

const data = (patch: Partial<DocumentVersions> = {}): DocumentVersions => ({
  name: "Services agreement.docx",
  document: { id: "doc-1", name: "Services agreement.docx", current_version: "v-4" },
  versions: [
    version(4, { current: true, origin: "restore", label: "Restored from version 2" }),
    version(3, { actor: "Pat Reviewer", label: "Their markup" }),
    version(2, { origin: "replace", removed: "redaction" }),
    version(1, { origin: "upload" }),
  ],
  events: [{ id: 1, kind: "restore", version_id: "v-4", actor: "unknown", detail: { restored_number: 2 }, created_at: at }],
  working_version: "v-4",
  ...patch,
})
const panel = (value: DocumentVersions, extra: Partial<Parameters<typeof VersionsPanel>[0]> = {}) => renderToStaticMarkup(createElement(VersionsPanel, {
  matterId: "m-1", name: "Services agreement.docx", data: value, unavailable: {}, onShow: () => {}, onCompare: () => {}, onRestored: () => {}, onUnavailable: () => {}, ...extra,
}))
const rows = (html: string) => [...html.matchAll(/<li class="version-row[^"]*"[^>]*>([\s\S]*?)<\/li>/g)].map(([, row]) => ({
  text: row!.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim(),
  buttons: [...row!.matchAll(/<button[^>]*>([\s\S]*?)<\/button>/g)].map(([, label]) => label!.replace(/<[^>]+>/g, "").trim()),
  // What a screen reader names each button, out of the row's context.
  names: [...row!.matchAll(/<button([^>]*)>([\s\S]*?)<\/button>/g)].map(([, attributes, label]) => /aria-label="([^"]*)"/.exec(attributes!)?.[1] ?? label!.replace(/<[^>]+>/g, "").trim()),
  disabled: [...row!.matchAll(/<button([^>]*)>/g)].map(([, attributes]) => / disabled=""/.test(attributes!)),
}))

describe("versions list", () => {
  test("lists every version newest first with what made it, who, when and its label; the current one is marked and not restorable", () => {
    const listed = rows(panel(data()))
    expect(listed.map((row) => row.text.match(/^Version \d+/)?.[0])).toEqual(["Version 4", "Version 3", "Version 2", "Version 1"])
    expect(listed[0]!.text).toStartWith("Version 4 Current Restored from version 2")
    // The default restore label only repeats the origin, so it is not shown twice.
    expect(listed[0]!.text.match(/Restored from version 2/g)).toHaveLength(1)
    expect(listed[0]!.buttons).toEqual(["Download", "Compare with version 3"])
    expect(listed[1]!.text).toContain("Saved from Word · by Pat Reviewer")
    expect(listed[1]!.text).toContain("Their markup")
    // Its earlier version's copy is gone, so there is nothing to compare it with.
    expect(listed[1]!.buttons).toEqual(["View", "Download", "Restore"])
    expect(listed[3]!.buttons).toEqual(["View", "Download", "Restore"])
    // Each button names its version, so a list of them read out of context still says which.
    expect(listed[1]!.names).toEqual(["View version 3", "Download version 3", "Restore version 3"])
  })

  test("the list says a redaction removes text from earlier versions", () => {
    expect(panel(data())).toContain("doc.haus keeps every version of this document, except text removed by a redaction.")
  })

  test("a version identical to the current one is not offered for restore", () => {
    const same = "a".repeat(64)
    const listed = rows(panel(data({ versions: [
      version(5, { current: true, origin: "restore", sha256: same }),
      version(4, { origin: "accept" }),
      version(3, { sha256: same }),
    ], working_version: "v-5" })))
    expect(listed[2]!.buttons).toEqual(["View", "Download"])
    expect(listed[1]!.buttons).toEqual(["View", "Download", "Compare with version 3", "Restore"])
  })

  test("while the list reloads its rows cannot be acted on", () => {
    const listed = rows(panel(data(), { loading: true }))
    expect(listed[1]!.disabled).toEqual([true, true, true])
    expect(rows(panel(data()))[1]!.disabled).toEqual([false, false, false])
  })

  test("where an older version cannot be shown, its row offers download and restore only", () => {
    const listed = rows(panel(data({ working_version: null }), { onShow: undefined, onCompare: undefined }))
    expect(listed.map((row) => row.buttons)).toEqual([["Download", "Restore"], ["Download", "Restore"], [], ["Download", "Restore"]])
  })

  test("a version whose kept copy was removed stays listed with the reason, and cannot be opened or restored", () => {
    const [, , removed] = rows(panel(data()))
    expect(removed!.text).toContain("Uploaded as a new version")
    expect(removed!.text).toContain("Removed when the document was redacted.")
    expect(removed!.buttons).toEqual([])
    // One found unreadable after the list loaded says why too.
    const [, damaged] = rows(panel(data(), { unavailable: { "v-3": "The kept copy of this version is missing or damaged." } }))
    expect(damaged!.text).toContain("The kept copy of this version is missing or damaged.")
    expect(damaged!.buttons).toEqual([])
  })

  test("a file changed outside doc.haus says so, and its current version can be viewed and restored", () => {
    const html = panel(data({ working_version: null }))
    expect(html).toContain("The file has changed outside doc.haus since the current version.")
    expect(rows(html)[0]!.buttons).toEqual(["View", "Download", "Compare with version 3", "Restore"])
  })

  test("an older version open in the viewer is marked, and the current one offers the way back", () => {
    const listed = rows(panel(data(), { shown: "v-3" }))
    expect(listed[1]!.text).toContain("Viewing")
    expect(listed[1]!.buttons[0]).toBe("Download")
    expect(listed[0]!.buttons[0]).toBe("View current")
  })

  test("a document with no kept versions yet says when they start", () => {
    expect(panel(data({ versions: [], working_version: null }))).toContain("No versions kept yet. doc.haus keeps one each time this document is saved, replaced or changed.")
  })

  test("the restore confirmation says it makes a new version and keeps the history", () => {
    expect(restoreConfirmText(2, 5)).toBe("This saves a copy of version 2 as version 5, the new current version. Nothing is deleted: every version stays in the history.")
    expect(restoreConfirmText(2)).toBe("This saves a copy of version 2 as the new current version. Nothing is deleted: every version stays in the history.")
    // A file changed outside doc.haus is kept as a version first, so the restore's number is not foretold.
    expect(restoreConfirmText(2, undefined, true)).toBe("This keeps the file's changes made outside doc.haus as a version, then saves a copy of version 2 as the new current version. Nothing is deleted: every version stays in the history.")
  })
})

describe("version requests", () => {
  test("compare sends a kept version per side, after the names", () => {
    expect(new URL(compareUrl("m-1", { left: "A.docx", right: "A.docx", leftVersion: "v-2", rightVersion: "v-3" })).search).toBe(
      "?left=A.docx&right=A.docx&leftVersion=v-2&rightVersion=v-3&ignoreFormatting=1&moves=1&headers=1&format=docx",
    )
    const options = { ignoreFormatting: true, detectMoves: true, headersFooters: true }
    // The previous version on the earlier side, this file's working copy on the later.
    expect(choiceParams({ name: "A.docx", other: "A.docx", otherVersion: "v-2", thisSide: "right", thisLabel: "A (version 3)", otherLabel: "A (version 2)", options })).toEqual({
      left: "A.docx", right: "A.docx", rightLabel: "A (version 3)", leftVersion: "v-2", leftLabel: "A (version 2)", ...options,
    })
    expect(choiceParams({ name: "A.docx", other: "B.docx", thisVersion: "v-1", thisSide: "left", thisLabel: "", otherLabel: "", options })).toEqual({
      left: "A.docx", right: "B.docx", leftVersion: "v-1", ...options,
    })
  })

  test("an unreadable or removed version's copy is told apart from other failures", async () => {
    globalThis.fetch = (async () => Response.json({ error: "The kept bytes of this version are missing or damaged.", code: "version_damaged" }, { status: 409 })) as unknown as typeof fetch
    expect(await fetchVersionBytes("m-1", "v-2").catch((error: unknown) => error)).toBeInstanceOf(VersionUnavailableError)
    expect(unavailableReason(await fetchVersionBytes("m-1", "v-2").catch((error: unknown) => error))).toBe("The kept copy of this version is missing or damaged.")
    globalThis.fetch = (async () => Response.json({ error: "Removed by redaction.", code: "removed_by_redaction" }, { status: 410 })) as unknown as typeof fetch
    const redacted = await fetchVersionBytes("m-1", "v-2").catch((error: unknown) => error)
    expect(redacted).toMatchObject({ status: 410, code: "removed_by_redaction" })
    expect(unavailableReason(redacted)).toBe("Removed when the document was redacted.")
    globalThis.fetch = (async () => new Response("gone", { status: 404 })) as unknown as typeof fetch
    expect(unavailableReason(await fetchVersionBytes("m-1", "v-2").catch((error: unknown) => error))).toBe("This version is no longer kept.")
    globalThis.fetch = (async () => new Response("down", { status: 502 })) as unknown as typeof fetch
    expect(await fetchVersionBytes("m-1", "v-2").catch((error: unknown) => error)).not.toBeInstanceOf(VersionUnavailableError)
  })

  test("restore posts to the version's route and a refusal keeps the route's words and code", async () => {
    const calls: { url: string; method?: string }[] = []
    globalThis.fetch = (async (input: string | URL | Request, init?: RequestInit) => {
      calls.push({ url: String(input), method: init?.method })
      return Response.json({ name: "A.docx", version: { id: "v-5", number: 5 }, restored_from: { id: "v-2", number: 2 } })
    }) as typeof fetch
    expect((await restoreVersion("m 1", "v-2")).version?.number).toBe(5)
    expect(calls).toHaveLength(1)
    expect(calls[0]!.url).toEndWith("/matters/m%201/documents/versions/v-2/restore")
    expect(calls[0]!.method).toBe("POST")
    globalThis.fetch = (async () => Response.json({ error: "A.docx already holds version 2.", code: "already_current" }, { status: 409 })) as unknown as typeof fetch
    const refused = await restoreVersion("m-1", "v-2").catch((error: unknown) => error)
    expect(refused).toBeInstanceOf(RestoreRefusedError)
    expect(refused).toMatchObject({ code: "already_current", message: "A.docx already holds version 2." })
    // A redaction-removed version's refusal reads as the list's reason; others keep the route's words.
    expect(unavailableReason(refused)).toBeUndefined()
    globalThis.fetch = (async () => Response.json({ error: "Removed by redaction.", code: "removed_by_redaction" }, { status: 410 })) as unknown as typeof fetch
    expect(unavailableReason(await restoreVersion("m-1", "v-2").catch((error: unknown) => error))).toBe("Removed when the document was redacted.")
  })
})
